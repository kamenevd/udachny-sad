/**
 * Задачи месяца для конкретного справочника. Общесадовые (без types)
 * показываются, только если растения вообще есть; типовые — если есть
 * растение подходящего типа.
 */
export function getSeasonalTasks(
  month: number,
  plants: Pick<Plant, 'plantType'>[],
): SeasonalTask[] {
  if (plants.length === 0) return [];
  const monthTasks = CALENDAR[month] ?? [];
  const ownedTypes = new Set(plants.map((p) => p.plantType));
  return monthTasks.filter(
    (task) => !task.types || task.types.some((t) => ownedTypes.has(t)),
  );
}
